export function translate(
  key: string,
  language: Language,
  variables: Record<string, string | number> = {}
): string {
  const value = STRINGS[key];
  if (!value) return key;
  const template = value[language] || value.en;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`));
}
